"""Generates the launcher icon drawables and a host-side preview from one geometry description.
usage: make_icon.py <res_dir> <preview.png>   (uv run --with pillow python tools/make_icon.py app/src/main/res preview.png)"""
import sys, math
from PIL import Image, ImageDraw

res, preview = sys.argv[1], sys.argv[2]
AMBER, TEAL = "FBBF24", "2DD4BF"
STROKE = 3.0
# (name, colour, box x,y,w,h, tag x,y,w,h, text-bar widths)  -- drawn back to front
BOXES = [
    ("amber", AMBER, (50, 38, 30, 24), (50, 30, 20, 8), (9,)),
    ("teal",  TEAL,  (29, 52, 29, 23), (29, 44, 20, 8), (9,)),
]
TEXT_DARK = {"amber": "1A1405", "teal": "04201C"}

def n(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return s if s else "0"

def tag_path(x, y, w, h, r=1.6):
    """Label shape: rounded on the left, pointed on the right (so it reads as a tag, not a folder tab)."""
    p = h / 2
    return (f"M{n(x+r)},{n(y)} H{n(x+w-p)} L{n(x+w)},{n(y+p)} L{n(x+w-p)},{n(y+h)} H{n(x+r)} "
            f"a{n(r)},{n(r)} 0 0 1 {n(-r)},{n(-r)} V{n(y+r)} a{n(r)},{n(r)} 0 0 1 {n(r)},{n(-r)} z")

def rrect(x, y, w, h, r):
    return (f"M{n(x+r)},{n(y)} h{n(w-2*r)} a{n(r)},{n(r)} 0 0 1 {n(r)},{n(r)} v{n(h-2*r)} "
            f"a{n(r)},{n(r)} 0 0 1 {n(-r)},{n(r)} h{n(-(w-2*r))} a{n(r)},{n(r)} 0 0 1 {n(-r)},{n(-r)} "
            f"v{n(-(h-2*r))} a{n(r)},{n(r)} 0 0 1 {n(r)},{n(-r)} z")

def text_bars(tag, widths):
    x, y, w, h = tag
    w = w - h / 2          # the label text sits in the body, not in the pointed end
    bh, gap = 2.6, 1.8
    total = sum(widths) + gap * (len(widths) - 1)
    cx = x + (w - total) / 2
    out = []
    for bw in widths:
        out.append(rrect(cx, y + (h - bh) / 2, bw, bh, bh / 2))
        cx += bw + gap
    return out

BOX_R, TAG_R = 2.5, 2.0

# Objects drawn inside the boxes: ("circle", cx, cy, r) or ("person", cx, base_y, head_r)
OBJECTS = {"amber": ("circle", 66, 51.5, 5.5), "teal": ("person", 43.5, 72.8, 3.2)}

def circle(cx, cy, r):
    return f"M{n(cx-r)},{n(cy)} a{n(r)},{n(r)} 0 1 1 {n(2*r)},0 a{n(r)},{n(r)} 0 1 1 {n(-2*r)},0 z"

def object_paths(obj):
    if obj[0] == "circle":
        return [circle(*obj[1:])]
    _, cx, by, hr = obj
    sw, sh = 6.5, 6.0     # half-width and height of the shoulders
    return [circle(cx, by - sh - hr - 0.9, hr), f"M{n(cx-sw)},{n(by)} a{n(sw)},{n(sh)} 0 0 1 {n(2*sw)},0 z"]

def path(fill=None, stroke=None, d="", extra=""):
    a = []
    if fill: a.append(f'        android:fillColor="#{fill}"')
    if stroke: a += [f'        android:strokeColor="#{stroke}"', f'        android:strokeWidth="{n(STROKE)}"',
                     '        android:strokeLineJoin="round"']
    if extra: a.append(extra)
    a.append(f'        android:pathData="{d}"')
    return "    <path\n" + "\n".join(a) + " />\n"

HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n')
VEC = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n'
       '    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n')

# foreground
fg = HEAD + ("<!-- Two detection boxes with their label tags (a label bar). All shapes stay inside the\n"
             "     66dp circle in the centre of the 108dp canvas, the adaptive-icon safe zone. Generated by tools/make_icon.py. -->\n") + VEC
for name, col, box, tag, bars in BOXES:
    fg += f"    <!-- {name} box -->\n"
    fg += path(fill="2E" + col, d=rrect(*box, BOX_R))
    fg += path(stroke="FF" + col, d=rrect(*box, BOX_R))
    for o in object_paths(OBJECTS[name]):
        fg += path(fill="80" + col, d=o)
    fg += path(fill="FF" + col, d=tag_path(*tag))
    for b in text_bars(tag, bars):
        fg += path(fill="FF" + TEXT_DARK[name], d=b)
fg += "</vector>\n"

# monochrome (themed icon): outlines + solid tags with the text cut out
mono = HEAD + "<!-- Single-colour version for Android 13+ themed icons. -->\n" + VEC
for name, col, box, tag, bars in BOXES:
    mono += path(stroke="FF000000", d=rrect(*box, BOX_R))
    mono += path(fill="FF000000", d=" ".join(object_paths(OBJECTS[name])))
    mono += path(fill="FF000000", d=tag_path(*tag) + " " + " ".join(text_bars(tag, bars)), extra='        android:fillType="evenOdd"')
mono += "</vector>\n"

bg = HEAD + ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n'
    '    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
    '    <path android:pathData="M0,0h108v108h-108z">\n        <aapt:attr name="android:fillColor">\n'
    '            <gradient\n                android:startX="0"\n                android:startY="0"\n                android:endX="108"\n'
    '                android:endY="108"\n                android:type="linear">\n'
    '                <item android:offset="0" android:color="#FF273449" />\n'
    '                <item android:offset="1" android:color="#FF0A101C" />\n            </gradient>\n'
    '        </aapt:attr>\n    </path>\n</vector>\n')

for fname, text in (("ic_launcher_foreground.xml", fg), ("ic_launcher_monochrome.xml", mono), ("ic_launcher_background.xml", bg)):
    open(f"{res}/drawable/{fname}", "w", newline="\n").write(text)

# ---- host preview with the same geometry ----
K = 8; W = 108 * K
def rr(d, x, y, w, h, r, fill=None, outline=None, width=0):
    d.rounded_rectangle([x*K, y*K, (x+w)*K, (y+h)*K], r*K, fill=fill, outline=outline, width=int(width*K))
def rgb(h, a=255): return tuple(int(h[i:i+2], 16) for i in (0, 2, 4)) + (a,)
bgi = Image.new("RGB", (W, W)); px = bgi.load()
c0, c1 = (0x27, 0x34, 0x49), (0x0A, 0x10, 0x1C)
for yy in range(W):
    for xx in range(W):
        t = (xx + yy) / (2 * (W - 1)); px[xx, yy] = tuple(round(a + (b - a) * t) for a, b in zip(c0, c1))
layer = Image.new("RGBA", (W, W), (0, 0, 0, 0)); d = ImageDraw.Draw(layer, "RGBA")
for name, col, box, tag, bars in BOXES:
    rr(d, *box, BOX_R, fill=rgb(col, 0x2E)); rr(d, *box, BOX_R, outline=rgb(col), width=STROKE)
    o = OBJECTS[name]
    if o[0] == "circle":
        _, cx, cy, r = o; d.ellipse([(cx-r)*K, (cy-r)*K, (cx+r)*K, (cy+r)*K], fill=rgb(col, 0x80))
    else:
        _, cx, by, hr = o; sw, sh = 6.5, 6.0; hy = by - sh - hr - 0.9
        d.ellipse([(cx-hr)*K, (hy-hr)*K, (cx+hr)*K, (hy+hr)*K], fill=rgb(col, 0x80))
        d.pieslice([(cx-sw)*K, (by-sh)*K, (cx+sw)*K, (by+sh)*K], 180, 360, fill=rgb(col, 0x80))
    x, y, w, h = tag
    d.polygon([((x+1)*K, y*K), ((x+w-h/2)*K, y*K), ((x+w)*K, (y+h/2)*K), ((x+w-h/2)*K, (y+h)*K), ((x+1)*K, (y+h)*K)], fill=rgb(col))
    rr(d, x, y, 3, h, 1.6, fill=rgb(col))
    w = w - h / 2; bh, gap = 2.6, 1.8; cx = x + (w - (sum(bars) + gap * (len(bars) - 1))) / 2
    for bw in bars:
        rr(d, cx, y + (h - bh) / 2, bw, bh, bh / 2, fill=rgb(TEXT_DARK[name])); cx += bw + gap
full = bgi.convert("RGBA"); full.alpha_composite(layer)

def masked(img, shape, size):
    m = Image.new("L", img.size, 0); dd = ImageDraw.Draw(m); pad = 18 * K; box = [pad, pad, W - pad, W - pad]
    if shape == "circle": dd.ellipse(box, fill=255)
    else: dd.rounded_rectangle(box, 18 * K, fill=255)
    out = Image.new("RGBA", img.size, (0, 0, 0, 0)); out.paste(img, (0, 0), m)
    return out.crop(box).resize((size, size), Image.LANCZOS)
sheet = Image.new("RGBA", (3 * 360 + 4 * 24, 360 + 48 + 130), (20, 22, 30, 255))
for i, shape in enumerate(("circle", "squircle")): sheet.alpha_composite(masked(full, shape, 360), (24 + i * 384, 24))
sheet.alpha_composite(full.resize((360, 360), Image.LANCZOS), (24 + 2 * 384, 24))
for j, s in enumerate((96, 64, 48)):
    sheet.alpha_composite(masked(full, "circle", s), (24 + j * 130, 24 + 360 + 24))
    sheet.alpha_composite(masked(full, "squircle", s), (24 + 400 + j * 130, 24 + 360 + 24))
sheet.convert("RGB").save(preview)
# safe-zone check: farthest painted pixel from the centre, in dp
a = layer.split()[3].point(lambda v: 255 if v > 40 else 0)
far = 0
for yy in range(0, W, 2):
    for xx in range(0, W, 2):
        if a.getpixel((xx, yy)):
            far = max(far, math.hypot(xx / K - 54, yy / K - 54))
print(f"farthest painted point from centre: {far:.1f} dp (safe-zone radius is 33)")
